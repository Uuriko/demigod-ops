#!/usr/bin/env node
import assert from 'node:assert/strict';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const write = process.argv.includes('--write');
const registryName = 'DASHA-DOC-REGISTRY.md';
const canonical = new Set(['DASHA-DOCS.md', 'DASHA-RULES.md', 'DASHA-WORKFLOW.md', 'DASHA-PRODUCT-BRIEF.md', 'DASHA-ROADMAP.md', 'DASHA-BIBLE.md']);
const retired = new Set(['DASHA-PRODUCT-STRATEGY.md', 'DASHA-DISCORD-BLUEPRINT.md', 'DASHA-SPEC-GAMIFICATION.md', 'DASHA-SPEC-SETTLEMENT.md']);

const files = readdirSync(root).filter(name => /^DASHA.*\.md$/.test(name) && name !== registryName).sort();
const parse = text => Object.fromEntries((text.match(/^---\n([\s\S]*?)\n---\n/)?.[1] || '').split('\n').map(line => {
  const at = line.indexOf(':');
  return at < 1 ? null : [line.slice(0, at).trim(), line.slice(at + 1).trim()];
}).filter(Boolean));
const inferredStatus = name => canonical.has(name) ? 'canonical'
  : name === 'DASHA-NOW.md' ? 'generated'
  : retired.has(name) || /-2026-\d{2}-\d{2}\.md$/.test(name) ? 'historical'
  : 'reference';

if (write) {
  for (const name of files) {
    const path = join(root, name), text = readFileSync(path, 'utf8');
    if (text.startsWith('---\n')) continue;
    const status = inferredStatus(name);
    const extra = status === 'historical' ? 'archived: 2026-08-08\n' : '';
    writeFileSync(path, `---\nstatus: ${status}\n${extra}---\n\n${text}`);
  }
}

const records = files.map(name => {
  const meta = parse(readFileSync(join(root, name), 'utf8'));
  assert(['canonical', 'reference', 'working', 'historical', 'generated'].includes(meta.status), `${name}: missing or invalid status`);
  return { name, ...meta };
});
const owners = records.filter(record => record.canonical_for);
assert.equal(new Set(owners.map(record => record.canonical_for)).size, owners.length, 'duplicate canonical_for ownership');

const rows = [...records, { name: registryName, status: 'generated', generated_from: 'top-level DASHA-*.md metadata' }]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(record => `| [${record.name}](${record.name}) | ${record.status} | ${record.canonical_for || record.superseded_by || record.generated_from || '—'} |`)
  .join('\n');
const output = `---\nstatus: generated\ngenerated_from: top-level DASHA-*.md metadata\n---\n\n# Dasha document registry\n\n> Generated by \`node dasha-doc-registry.mjs --write\`. Do not edit by hand.\n\n| Document | Lifecycle | Owner / disposition |\n|---|---|---|\n${rows}\n`;
const registryPath = join(root, registryName);
if (write) writeFileSync(registryPath, output);
else assert.equal(readFileSync(registryPath, 'utf8'), output, `${registryName} is stale; run node dasha-doc-registry.mjs --write`);

console.log(`dasha docs registry: PASS (${records.length + 1} classified documents)`);
