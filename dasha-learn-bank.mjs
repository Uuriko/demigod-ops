export const MODULE_BY_ID = new Map(MODULES.map((row) => [row.id, row]));

export function modulesForTrack(track) {
  return MODULES.filter((row) => row.track === track);
}

export function publicModule(row) {
  if (!row) return null;
  return {
    id: row.id,
    track: row.track,
    skill: row.skill,
    difficulty: row.difficulty,
    points: row.points,
    tool: row.tool || null,
    goal: row.goal,
    type: row.type,
    body: row.body || '',
    prompt: row.prompt || '',
    choices: row.choices || null,
    answer: row.answer ?? null,
    proves: row.proves || null,
    items: row.items || null,
    chips: row.chips || null,
    hop: row.hop || null,
    pass: row.pass || 'correct',
    note: row.note || '',
    source: row.source || '',
    surprise: row.surprise || null,
    fallback: row.fallback || null,
  };
}

export function publicBank() {
  return {
    mint: MINT,
    source: MINT_SOURCE,
    notDev: NOT_DEV,
    jupiter: JUPITER,
    solscan: SOLSCAN,
    tracks: TRACKS,
    modules: MODULES.map(publicModule),
  };
}

export function isLearnTrack(track) {
  return Boolean(TRACKS[track]);
}

export function isLearnModuleId(id) {
  return MODULE_BY_ID.has(String(id || ''));
}
