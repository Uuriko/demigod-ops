#!/usr/bin/env node
/**
 * Puts the verified chess engine into the chess page so a visitor can play without an account.
 *
 * The engine already existed and was already correct — dasha-chess-rules.test.mjs proves it on the
 * cases engines get wrong — but it ran only inside the Durable Object. The browser had no
 * legalMoves and no playMove, which is why /chess could show nothing at all until you linked X.
 *
 * This copies it in rather than reimplementing it, because a second chess engine written for the
 * client would be a second set of rules, and the two would disagree on exactly the edge cases the
 * first one gets right. dasha-chess.mjs stays the single source of truth; the page carries a
 * generated copy between markers, and --check fails when the copy drifts from the source.
 *
 * Only the engine is generated. The local-play UI is hand-written in the page, where it belongs.
 *
 *   node dasha-chess-local-build.mjs           # inject into dasha-chess-page.html
 *   node dasha-chess-local-build.mjs --check    # exit 1 if the injected copy is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes('--check');
const PAGE = join(root, 'dasha-chess-page.html');
const START = '<!-- CHESS-ENGINE:START — generated by dasha-chess-local-build.mjs, do not edit -->';
const END = '<!-- CHESS-ENGINE:END -->';

/** The engine, as a plain script exposing exactly what the local game needs. */
export function engineBlock() {
  const src = readFileSync(join(root, 'dasha-chess.mjs'), 'utf8');
  if (/^\s*import\s/m.test(src)) throw new Error('the engine gained an import and can no longer be inlined');
  if (/require\(|process\.|node:/.test(src)) throw new Error('the engine gained a Node-only API and cannot run in a browser');
  const script = src.replace(/^export /gm, '');
  /* Named explicitly. A blanket re-export would quietly widen the page's surface every time the
     engine grows a helper, and the page should depend on the few functions it actually uses. */
  const exposed = ['newChessState', 'legalMoves', 'playMove', 'squareIndex', 'squareName', 'inCheck', 'resignChess'];
  for (const name of exposed) {
    if (!new RegExp(`function ${name}\\b`).test(src)) throw new Error(`the engine no longer exports ${name}`);
  }
  return `${START}\n<script>\n(function(){\n${script}\nwindow.DashaChessEngine={${exposed.join(',')}};\n})();\n</script>\n${END}`;
}

const page = readFileSync(PAGE, 'utf8');
const from = page.indexOf(START);
const to = page.indexOf(END);
if (from < 0 || to < 0) throw new Error(`markers missing in dasha-chess-page.html — expected ${START}`);
const current = page.slice(from, to + END.length);
const wanted = engineBlock();

if (check) {
  if (current !== wanted) {
    console.error('dasha-chess-page.html carries a stale copy of the engine — run: node dasha-chess-local-build.mjs');
    process.exit(1);
  }
  console.log('dasha chess local engine: current');
} else {
  writeFileSync(PAGE, page.slice(0, from) + wanted + page.slice(to + END.length));
  console.log(`dasha chess local engine: injected ${wanted.length} chars into dasha-chess-page.html`);
}
